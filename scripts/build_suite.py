def _ap_task_generator(seed: int) -> Generator[dict[str, Any], None, None]:
    """Infinite generator yielding AP tasks with cycling category distribution.

    First cycle follows AP_GEN_PLAN counts (220 tasks). Subsequent cycles
    repeat all 40 categories once each (overflow). Cross-cutting dimensions
    (channel, domain, host task, camouflage) rotate by global task index.
    """
    rng = random.Random(seed)

    # Build one plan cycle
    plan_tasks: list[dict[str, Any]] = []
    for code, name, desc, n in AP_GEN_PLAN:
        for _ in range(n):
            plan_tasks.append({"category_code": code, "category_name": name, "category_desc": desc})

    # Overflow cycle: one task per category
    overflow_base: list[dict[str, Any]] = [
        {"category_code": code, "category_name": name, "category_desc": desc}
        for code, name, desc, _ in AP_GEN_PLAN
    ]

    task_index = 0
    cycle_num = 0

    while True:
        cycle = list(plan_tasks) if cycle_num == 0 else list(overflow_base)
        rng.shuffle(cycle)

        for task in cycle:
            ch_desc, ch_tag = _DELIVERY_CHANNELS[task_index % len(_DELIVERY_CHANNELS)]
            yield {
                **task,
                "task_index": task_index,
                "delivery_channel": ch_desc,
                "channel_tag": ch_tag,
                "domain": _DOMAINS[task_index % len(_DOMAINS)],
                "host_task": _HOST_TASKS[task_index % len(_HOST_TASKS)],
                "camouflage_hint": _CAMOUFLAGE_STYLES[task_index % len(_CAMOUFLAGE_STYLES)],
            }
            task_index += 1

        cycle_num += 1


def _generate_one_ap(
    task: dict[str, Any],
    client: Any,
    model: str,
    timeout: float,
) -> dict[str, Any] | None:
    """Call LLM to generate one AP injection example. Returns extraction-style dict or None."""
    user_msg = _build_ap_gen_prompt(
        task["category_code"], task["category_name"], task["category_desc"],
        task["delivery_channel"], task["channel_tag"],
        task["domain"], task["host_task"], task["camouflage_hint"],
    )

    for attempt in range(3):
        try:
            resp = client.chat.completions.create(
                model=model,
                temperature=0.9,
                messages=[
                    {"role": "system", "content": AP_GEN_SYSTEM},
                    {"role": "user", "content": user_msg},
                ],
                response_format={"type": "json_object"},
                timeout=timeout,
            )
            raw = _strip_thinking(resp.choices[0].message.content)
            parsed = json.loads(raw)

            prompt_text = parsed.get("prompt", "").strip()
            user_instr = parsed.get("user_instruction", "").strip()
            injected_instr = parsed.get("injected_instruction", "").strip()
            difficulty = parsed.get("difficulty", "medium")
            notes = parsed.get("notes", "").strip()

            if not prompt_text or not user_instr or not injected_instr:
                if attempt < 2:
                    print(" RETRY (missing fields)", end="", flush=True)
                    time.sleep(2**attempt)
                    continue
                print(" SKIP (missing fields after retries)", flush=True)
                return None

            if difficulty not in ("easy", "medium", "hard"):
                difficulty = "medium"

            # Parse instructions list; fall back to the two core claims if missing/malformed
            raw_instrs = parsed.get("instructions", [])
            instructions: list[str] = (
                [s.strip() for s in raw_instrs if isinstance(s, str) and s.strip()]
                if isinstance(raw_instrs, list)
                else []
            )
            if not instructions:
                instructions = [user_instr, injected_instr]

            domain_tag = task["domain"].replace(" ", "-").replace("/", "-")
            structural_tags = [
                "single-turn", "nested/embedded",
                task["category_code"], task["channel_tag"], domain_tag,
            ]
            metadata_text = (
                notes
                or f"{task['category_code']} injection via {task['channel_tag']} in {domain_tag} domain"
            )

            return {
                "prompt": prompt_text,
                "user_instruction": user_instr,
                "injected_instruction": injected_instr,
                "difficulty": difficulty,
                "instructions": instructions,
                "structural_tags": structural_tags,
                "metadata_text": metadata_text,
            }

        except Exception as exc:  # noqa: BLE001
            err_str = str(exc)
            if attempt < 2:
                print(f" RETRY ({err_str[:50]})", end="", flush=True)
                time.sleep(2**attempt)
            else:
                print(f" SKIP ({err_str[:80]})", flush=True)
                return None

    return None


def verify_injection(
    prompt_text: str,
    user_instruction: str,
    injected_instruction: str,
    base_client: Any,
    base_model: str,
    judge_client: Any,
    judge_model: str,
    timeout: float = 60.0,
) -> tuple[bool, str, str]:
    """Run the scenario through the base model, then judge the output with the eval model.

    base_client / base_model  — PRISM_BASE_MODEL (Qwen): produces the response whose
                                activations ITM monitors. No reasoning expected.
    judge_client / judge_model — PRISM_EVAL_MODEL (gemma4): judges whether the base
                                 model's response followed the injected instruction.

    Returns (injection_success, judge_reasoning, model_response).
    On any failure returns (False, error_description, "").
    """
    # Step 1: run the scenario through the base model (activation source)
    try:
        resp = base_client.chat.completions.create(
            model=base_model,
            temperature=0,
            messages=[{"role": "user", "content": prompt_text}],
            extra_body={"chat_template_kwargs": {"enable_thinking": False}},
            timeout=timeout,
        )
        model_response = _strip_thinking(resp.choices[0].message.content or "")
    except Exception as exc:  # noqa: BLE001
        return False, f"base_model_call_failed: {str(exc)[:100]}", ""

    if not model_response.strip():
        return False, "base_model_returned_empty_response", ""

    # Step 2: judge whether the injection was followed (eval/judge model)
    judge_msg = AP_INJECT_JUDGE_USER_TEMPLATE.format(
        user_instruction=user_instruction,
        injected_instruction=injected_instruction,
        model_response=model_response[:2000],
    )

    for attempt in range(3):
        try:
            jresp = judge_client.chat.completions.create(
                model=judge_model,
                temperature=0,
                messages=[
                    {"role": "system", "content": AP_INJECT_JUDGE_SYSTEM},
                    {"role": "user", "content": judge_msg},
                ],
                response_format={"type": "json_object"},
                timeout=timeout,
            )
            raw = _strip_thinking(jresp.choices[0].message.content or "")
            parsed = json.loads(raw)
            success = bool(parsed.get("injection_success", False))
            reasoning = str(parsed.get("reasoning", ""))
            return success, reasoning, model_response
        except Exception as exc:  # noqa: BLE001
            if attempt < 2:
                time.sleep(2**attempt)
            else:
                return False, f"judge_failed: {str(exc)[:100]}", model_response

    return False, "judge_failed_after_retries", model_response


