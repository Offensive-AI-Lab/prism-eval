def _strip_thinking(text: str) -> str:
    """Remove <think>...</think> blocks emitted by Qwen3 reasoning mode."""
    if "<think>" in text and "</think>" in text:
        return text.split("</think>", 1)[-1].strip()
    return text.strip()


