def fetch_bn(count: int, max_chars: int, seed: int) -> list[tuple[str, str]]:
    """Fetch Benign Baseline samples from tatsu-lab/alpaca."""
    from datasets import load_dataset  # type: ignore

    ds = load_dataset("tatsu-lab/alpaca", split="train")
    rows = ds.to_list()
    rng = random.Random(seed)
    pool = [
        (row["instruction"].strip(), "alpaca:instruction")
        for row in rows
        if row.get("instruction")
        and not row.get("input", "").strip()
        and 20 <= len(row["instruction"].strip()) <= max_chars
    ]
    sampled = rng.sample(pool, min(count, len(pool)))
    print(f"  [BN] Loaded {len(sampled)} benign samples from {len(pool)} filtered rows")
    return sampled


# Strict role/persona-with-constraints filter for BC.
# The fka/prompts.chat dataset has grown beyond its original "Awesome ChatGPT
# Prompts" act-as charter and now mixes in image-gen, coding tasks, content
# drafts, structured templates, etc. BC is meant to test behavioral constraints
# attached to an explicitly assigned role, so we keep only prompts that
# explicitly assign a persona/role at (or near) the start.
_BC_PERSONA_PATTERNS = [
    r"i want you to act (as|like)\b",
    r"^i want you to (be|behave|respond|speak|talk) (as|like)\b",
    r"^act (as|like) (a|an|the)\b",
    r"^act (as|like) [A-Z]",
    r"^pretend (to be|you are|you'?re)\b",
    r"^imagine (you are|yourself as)\b",
    r"^you are (a|an|the|going to|now|to act|to be|my)\b",
    r"^you'?re (a|an|the)\b",
    r"^you will (be|act|play|now|take|assume)\b",
    r"^play the role of\b",
    r"^(assume|take on) the role\b",
    r"^role[:\-]",
    r"^your role is\b",
    r"^persona[:\-]",
    r"^character[:\-]",
    r"^you (must|should|will) (act|behave|respond) (as|like)\b",
]
_BC_PERSONA_RE = re.compile("|".join(_BC_PERSONA_PATTERNS), re.IGNORECASE | re.MULTILINE)


def _is_bc_persona_prompt(prompt: str) -> bool:
    return bool(_BC_PERSONA_RE.search(prompt[:300]))


def fetch_bc(count: int, max_chars: int, seed: int) -> list[tuple[str, str]]:
    """Fetch Behavioral Constraints samples from fka/prompts.chat.

    Filters to prompts that explicitly assign a role/persona (the BC pattern:
    a role identity followed by constraints on how the assistant should behave
    in that role).
    """
    from datasets import load_dataset  # type: ignore

    ds = load_dataset("fka/prompts.chat", split="train")
    rows = ds.to_list()
    if rows:
        print(f"  [BC] prompts.chat columns: {sorted(rows[0].keys())}")

    rng = random.Random(seed)
    raw_pool = [
        row for row in rows
        if row.get("prompt") and 20 <= len(row["prompt"].strip()) <= max_chars
        and row.get("type") != "IMAGE"
    ]
    pool = [
        (row["prompt"].strip(), f"prompts.chat:{row.get('act', 'unknown')}")
        for row in raw_pool
        if _is_bc_persona_prompt(row["prompt"].strip())
    ]
    print(
        f"  [BC] Persona-filter kept {len(pool)} / {len(raw_pool)} rows "
        f"({100 * len(pool) / max(len(raw_pool), 1):.1f}%) "
        f"(dropped {len(raw_pool) - len(pool)} non-persona prompts)."
    )
    if not pool:
        raise ValueError("fka/prompts.chat returned no persona-style rows — check filter.")

    if len(pool) < count:
        sampled = rng.choices(pool, k=count)
        print(
            f"  [BC] Persona-filtered pool has {len(pool)} prompts (< {count}). "
            f"Sampling with replacement to reach {count}."
        )
    else:
        sampled = rng.sample(pool, count)
    print(f"  [BC] Loaded {len(sampled)} BC samples from {len(pool)} filtered rows")
    return sampled


