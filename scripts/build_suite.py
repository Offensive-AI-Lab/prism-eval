def _dataset_name(source_tag: str) -> str:
    return source_tag.split(":")[0]


def build_record(
    eval_id: str,
    setting: str,
    prompt_text: str,
    extraction: dict[str, Any],
    source_tag: str,
    extra_metadata: dict[str, Any] | None = None,
    prompt_messages: list[dict] | None = None,
    category: str | None = None,
) -> dict[str, Any]:
    """Build a v2 EvalRecord dict from extracted metadata.

    ``prompt_messages`` (optional) attaches a structured conversation so the
    runner can place untrusted content in a tool/document turn (XPIA framing);
    ``prompt_text`` is still set so the scorers (judge + adversarial identifier),
    which read ``prompt``, see the full text including the injection.
    ``category`` overrides the per-setting default (e.g. "Indirect Prompt
    Injection" for the xpia XPIA suite while keeping setting="AP").
    """
    meta = SETTING_META[setting]
    metadata: dict[str, Any] = {
        meta["metadata_key"]: extraction["metadata_text"],
        "_source_tag": source_tag,
    }
    if extra_metadata:
        metadata.update(extra_metadata)

    return {
        "schema_version": "2.0",
        "eval_id": eval_id,
        "setting": setting,
        "category": category or meta["category"],
        "structural_tags": extraction["structural_tags"],
        "difficulty": extraction["difficulty"],
        "source": _dataset_name(source_tag),
        "prompt": prompt_text,
        "prompt_turns": None,
        "prompt_messages": prompt_messages,
        "generation_params": None,
        "instruction_positions": None,
        "model_override": None,
        "instruction_sources": {"original": extraction["instructions"]},
        "metadata": metadata,
        "probe_points": [
            {
                "probe_id": "p1",
                "location": "end_of_response",
                "expected_instructions": ["original"],
            }
        ],
    }


