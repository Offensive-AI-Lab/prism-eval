def extract_instructions(
    prompt_text: str,
    setting: str,
    client: Any,
    model: str,
    retries: int = 3,
    timeout: float = 30.0,
) -> dict[str, Any]:
    """Call the LLM to extract structured metadata from a raw prompt."""
    meta = SETTING_META[setting]
    template = EXTRACT_TEMPLATES[setting]
    user_msg = template.format(
        prompt=prompt_text[:1500],
        valid_tags=", ".join(f'"{t}"' for t in sorted(VALID_TAGS)),
        fields=_FIELDS.format(
            valid_tags=", ".join(f'"{t}"' for t in sorted(VALID_TAGS)),
            metadata_key=meta["metadata_key"],
        ),
    )

    for attempt in range(retries):
        try:
            resp = client.chat.completions.create(
                model=model,
                temperature=0.3,
                messages=[
                    {"role": "system", "content": EXTRACT_SYSTEM},
                    {"role": "user", "content": user_msg},
                ],
                response_format={"type": "json_object"},
                timeout=timeout,
            )
            raw = resp.choices[0].message.content
            parsed = json.loads(raw)

            instructions = parsed.get("instructions", [])
            difficulty = parsed.get("difficulty", "medium")
            tags = [t for t in parsed.get("structural_tags", []) if t in VALID_TAGS]
            metadata_text = parsed.get("metadata_text", "")

            if not instructions:
                instructions = ["[extraction returned empty — check prompt]"]
            if difficulty not in ("easy", "medium", "hard"):
                difficulty = "medium"
            if not tags:
                tags = ["single-turn", "explicit"]

            return {
                "instructions": instructions,
                "difficulty": difficulty,
                "structural_tags": tags,
                "metadata_text": metadata_text,
            }
        except Exception as exc:  # noqa: BLE001
            err_str = str(exc)
            if attempt < retries - 1:
                print(f" RETRY ({err_str[:60]})", end="", flush=True)
                time.sleep(2**attempt)
            else:
                print(f" SKIP ({err_str[:80]})", flush=True)
                return PLACEHOLDER_EXTRACTION.copy()

    return PLACEHOLDER_EXTRACTION.copy()


