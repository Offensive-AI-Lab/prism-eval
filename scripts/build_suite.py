def generate_ap(
    count: int,
    gen_client: Any,
    gen_model: str,
    seed: int,
    progress_path: Path = AP_GEN_PROGRESS_DEFAULT,
    timeout: float = 60.0,
    verify: bool = True,
    verify_client: Any = None,
    verify_model: str = "",
    regen_instructions: bool = False,
    force_regen_instructions: bool = False,
) -> tuple[list[APSample], list[APSample]]:
    """Generate AP prompt injection examples via LLM.

    gen_client / gen_model  — used for generating injection scenarios (PRISM_EVAL_* credentials).
    verify_client / verify_model — used for running the victim model and judging success
                                   (AP_TARGET_* credentials). Falls back to gen_client/gen_model
                                   if not provided.

    With verify=True (default): runs each example through the target model and judges
    whether the injection succeeded. Continues generating until `count` successes are
    collected (capped at count*5 total attempts to avoid infinite loops).

    With verify=False: generates exactly `count` examples with no success filtering.

    Resumable: saves each result to progress_path immediately.
    Returns (success_samples, failed_samples) — both are lists of APSample 3-tuples.
    """
    _verify_client = verify_client or gen_client
    _verify_model = verify_model or gen_model
    task_gen = _ap_task_generator(seed)

    # Load existing progress
    completed: dict[int, dict] = {}
    if progress_path.exists():
        for line in progress_path.read_text(encoding="utf-8").splitlines():
            if line.strip():
                try:
                    row = json.loads(line)
                    completed[row["task_index"]] = row
                except json.JSONDecodeError:
                    pass

    # Count existing successes and failures from prior runs
    if verify:
        n_success = sum(1 for r in completed.values() if r.get("injection_success") is True)
        n_failed = sum(1 for r in completed.values() if r.get("injection_success") is False)
    else:
        n_success = len(completed)
        n_failed = 0

    max_task_index = max(completed.keys(), default=-1)

    if completed:
        status = f"{n_success} successes, {n_failed} failed" if verify else f"{n_success} generated"
        print(f"  [AP] Resuming: {len(completed)} rows in progress file ({status})")

    # Optional: re-extract richer instructions + notes for cached rows that still have the old
    # 2-item format. Updates completed in-place and rewrites the progress JSONL.
    if (regen_instructions or force_regen_instructions) and completed:
        stale = (
            list(completed.values())
            if force_regen_instructions
            else [r for r in completed.values() if len(r.get("instructions", [])) <= 2]
        )
        if stale:
            print(f"  [AP] Regenerating instructions for {len(stale)} cached rows...")
            updated_count = 0
            for row in stale:
                idx = row["task_index"]
                result = _regen_one_ap_instructions(row, gen_client, gen_model, timeout)
                if result:
                    instrs, notes = result
                    completed[idx]["instructions"] = instrs
                    completed[idx]["metadata_text"] = notes or completed[idx].get("metadata_text", "")
                    updated_count += 1
                    print(f"    [{updated_count}/{len(stale)}] task {idx}: {len(instrs)} instructions")
                else:
                    print(f"    task {idx}: regen failed, keeping old instructions")
            # Rewrite progress JSONL with updated rows
            progress_path.write_text(
                "\n".join(json.dumps(r, ensure_ascii=False) for r in sorted(completed.values(), key=lambda r: r["task_index"])) + "\n",
                encoding="utf-8",
            )
            print(f"  [AP] Updated {updated_count}/{len(stale)} rows — progress file rewritten.")
        else:
            print("  [AP] All cached rows already have richer instructions — nothing to regen.")

    # Advance the generator past already-completed tasks
    for _ in range(max_task_index + 1):
        next(task_gen)

    max_attempts = count * 5 if verify else count
    total_attempts = len(completed)

    progress_path.parent.mkdir(parents=True, exist_ok=True)
    with progress_path.open("a", encoding="utf-8") as fp:
        while n_success < count and total_attempts < max_attempts + len(completed):
            task = next(task_gen)
            idx = task["task_index"]

            # Skip if already in progress (shouldn't happen after advancing, but safety check)
            if idx in completed:
                continue

            cat = task["category_code"]
            dom = task["domain"]
            ch = task["channel_tag"]
            total_attempts += 1
            success_label = f"{n_success}/{count}" if verify else f"{n_success}/{count}"
            print(
                f"  [{total_attempts:3d}] {cat} | {dom} | {ch} | ok={success_label}",
                end="", flush=True,
            )

            # Generate
            result = _generate_one_ap(task, gen_client, gen_model, timeout)
            if result is None:
                continue

            row: dict[str, Any] = {**task, **result}

            # Verify: base model produces response, gen/judge model scores it
            if verify:
                inj_success, reasoning, model_response = verify_injection(
                    result["prompt"],
                    result["user_instruction"],
                    result["injected_instruction"],
                    base_client=_verify_client,
                    base_model=_verify_model,
                    judge_client=gen_client,
                    judge_model=gen_model,
                    timeout=timeout,
                )
                row["injection_success"] = inj_success
                row["judge_reasoning"] = reasoning
                row["model_response"] = model_response

                label = "PASS" if inj_success else "FAIL"
                print(f" {label} — {reasoning[:70]}", flush=True)

                if inj_success:
                    n_success += 1
                else:
                    n_failed += 1
            else:
                row["injection_success"] = None  # not verified
                print(" OK", flush=True)
                n_success += 1

            fp.write(json.dumps(row, ensure_ascii=False) + "\n")
            fp.flush()
            completed[idx] = row

    if verify and n_success < count:
        print(
            f"\n  [AP] WARNING: reached attempt cap ({max_attempts}) with only "
            f"{n_success}/{count} successes. Increase --ap-max-attempts or check model quality.",
            file=sys.stderr,
        )

    # Separate successes and failures
    success_samples: list[APSample] = []
    failed_samples: list[APSample] = []

    for row in sorted(completed.values(), key=lambda r: r["task_index"]):
        is_success = row.get("injection_success") is not False  # True or None (unverified)
        extra_meta = {
            "injection_category": row["category_code"],
            "injection_category_name": row["category_name"],
            "delivery_channel": row["channel_tag"],
            "domain": row["domain"],
            "_extraction": {
                "instructions": row["instructions"],
                "difficulty": row["difficulty"],
                "structural_tags": row["structural_tags"],
                "metadata_text": row["metadata_text"],
            },
        }
        if verify:
            extra_meta["injection_success"] = row.get("injection_success")
            extra_meta["judge_reasoning"] = row.get("judge_reasoning", "")

        sample: APSample = (row["prompt"], "generated:ap_injection", extra_meta)

        if is_success:
            if len(success_samples) < count:
                success_samples.append(sample)
        else:
            failed_samples.append(sample)

    print(
        f"  [AP] Done: {len(success_samples)} successes, {len(failed_samples)} failed injections"
    )
    return success_samples, failed_samples


